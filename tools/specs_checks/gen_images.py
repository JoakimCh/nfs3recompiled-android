"""Writes the guest memory's seed for specs_checks: the whole code segment
(and the data group) as the game's own images keep them, so the names, the
ids, the format strings and every jump table the transcriptions read are the
game's own.

    python3 gen_images.py <disassembly dir> <build dir>
"""
import re
import sys
from pathlib import Path


def load_array(path, name):
    text = Path(path).read_text(errors="replace")
    start = text.index(name)
    braces = text.index("[]", start)
    body = text[braces:text.index("};", braces)]
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))


def main():
    source = Path(sys.argv[1])
    build = Path(sys.argv[2])
    build.mkdir(parents=True, exist_ok=True)
    auto = load_array(source / "nfs3hp.AUTO.cpp", "s_AUTOSegment")
    dgroup = load_array(source / "nfs3hp.DGROUP.cpp", "s_DGROUPSegment")
    (build / "auto.bin").write_bytes(auto)
    with (build / "spec_images.h").open("w") as f:
        f.write("/* Generated by gen_images.py: the game's data group, and where\n"
                " * gen_images.py left the code segment's image. */\n")
        f.write("#ifndef NFS3HP_SPEC_IMAGES_H\n#define NFS3HP_SPEC_IMAGES_H\n"
                "#include <lib/winapp.h>\n")
        f.write(f'#define SPEC_AUTO_BIN "{build / "auto.bin"}"\n')
        f.write(f"constexpr unsigned g_auto_len = {len(auto)};\n")
        f.write(f"constexpr x86::reg32 g_dgroup_at = 0x{0x536000:x};\n")
        f.write(f"constexpr unsigned g_dgroup_len = {len(dgroup)};\n")
        f.write("const x86::reg8 g_dgroup[] = {\n")
        for i in range(0, len(dgroup), 16):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in dgroup[i:i + 16]) + ",\n")
        f.write("};\n#endif\n")


if __name__ == "__main__":
    main()
